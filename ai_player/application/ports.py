"""Contracts implemented by provider and platform adapters."""

from __future__ import annotations

from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Protocol


class SpeechSynthesizer(Protocol):
    def synthesize(self, text: str, output_path: Path, voice: str | None = None) -> None: ...
    def set_cancel_callback(self, callback: Callable[[], bool]) -> None: ...
    def close(self) -> None: ...


class Translator(Protocol):
    def translate(self, text: str, source_language: str | None = None) -> str: ...
    def translate_many(self, texts: Sequence[str], source_language: str | None = None) -> list[str]: ...


class ManagedWorker(Protocol):
    def stop(self) -> None: ...
    def wait(self, milliseconds: int = 0) -> bool: ...
    def isRunning(self) -> bool: ...


class ProgressSink(Protocol):
    def __call__(self, completed: int, total: int, detail: str = "") -> None: ...
